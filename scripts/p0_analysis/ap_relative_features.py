"""AP-relative feature cache (v2).

Per-row features derived from the lab-measured ground-truth AP coordinates
(`config.AP_TRUTH`):
    - dist_to_AP                (m, Euclidean)
    - angle_to_AP_ego           (rad, [-pi, pi], AP bearing in AGV ego frame)
    - sin_angle_to_AP, cos_angle_to_AP
    - is_AP_in_FOV              (bool, using empirical valid sector)
    - clutter_frac_toward_AP    (fraction of beams within +-15° of AP bearing
                                 returning < 4000 mm; NaN if AP out of FOV)

Output: cache/ap_relative_features_v2.parquet — columns above + joint_idx.

Phase 1's frozen feature extractor consumes this cache (alongside the LiDAR
scalar feature cache and the anomaly mask). It is regenerated by the delta;
the v1 equivalent (computed against the path-loss-fitted AP) is now superseded.
"""
from __future__ import annotations

import h5py
import numpy as np
import pandas as pd

from . import config as C
from .io_utils import load_joint, read_json


CACHE_PATH = C.CACHE_DIR / "ap_relative_features_v2.parquet"

CLUTTER_MM = 4000.0
TOWARD_AP_HALF_WIDTH_DEG = 15.0
CHUNK_ROWS = 20000


def _wrap_to_pi(a: np.ndarray) -> np.ndarray:
    return (a + np.pi) % (2 * np.pi) - np.pi


def _compute_clutter_toward_ap_chunk(
    distances: np.ndarray,           # (n_rows, N_BEAMS) uint16
    angle_to_ap_ego: np.ndarray,     # (n_rows,) rad
    is_in_fov: np.ndarray,           # (n_rows,) bool
    mask_invalid: np.ndarray,        # (N_BEAMS,) bool
    beam_angles_rad: np.ndarray,     # (N_BEAMS,) rad
    fov_min_rad: float,
    fov_max_rad: float,
    half_width_rad: float,
) -> np.ndarray:
    """For each row in the chunk, compute clutter_frac_toward_AP.

    Uses circular distance to the AP bearing so a bearing of -179° matches
    a beam at +179°. Sets NaN where the AP is out of FOV (the row mask).
    """
    s = distances.astype(np.float32)
    bad = (s == 0) | (s == C.INVALID_FAR) | mask_invalid[None, :]
    is_close = np.where(bad, False, s < CLUTTER_MM)

    in_valid_sector = (beam_angles_rad >= fov_min_rad) & \
                      (beam_angles_rad <= fov_max_rad)
    # diff[r, b] = circular |beam_angle_b - angle_to_ap_ego_r|
    diff = beam_angles_rad[None, :] - angle_to_ap_ego[:, None]
    diff = (diff + np.pi) % (2 * np.pi) - np.pi
    near_ap = np.abs(diff) <= half_width_rad

    eligible = (~bad) & in_valid_sector[None, :] & near_ap
    n_eligible = eligible.sum(axis=1)
    n_close = (eligible & is_close).sum(axis=1)

    out = np.full(distances.shape[0], np.nan, dtype=np.float32)
    has_any = n_eligible > 0
    out[has_any] = n_close[has_any] / n_eligible[has_any]
    out[~is_in_fov] = np.nan
    return out


def compute_and_cache(force: bool = False) -> pd.DataFrame:
    if CACHE_PATH.exists() and not force:
        return pd.read_parquet(CACHE_PATH)

    fov = read_json(C.ARTIFACTS_DIR / "lidar_fov.json")
    mask_invalid = np.load(C.ARTIFACTS_DIR / "agv_body_mask.npz")["mask_invalid"]

    fov_min_rad = float(np.deg2rad(fov["theta_min_deg"]))
    fov_max_rad = float(np.deg2rad(fov["theta_max_deg"]))
    half_width_rad = float(np.deg2rad(TOWARD_AP_HALF_WIDTH_DEG))

    beam_angles_deg = C.ANGLE_MIN_DEG + np.arange(C.N_ACTIVE_BEAMS) * C.ANGLE_STEP_DEG
    beam_angles_full = np.zeros(C.N_BEAMS, dtype=np.float64)
    beam_angles_full[:C.N_ACTIVE_BEAMS] = beam_angles_deg
    beam_angles_rad = np.deg2rad(beam_angles_full)

    cols = ["session_date", "x_m", "y_m", "heading_rad", "lidar_row"]
    jp = load_joint(cols)
    n = len(jp)

    # Ground-truth AP per row
    x_ap = np.empty(n, dtype=np.float64)
    y_ap = np.empty(n, dtype=np.float64)
    for sd in C.SESSIONS:
        m = (jp["session_date"] == sd).to_numpy()
        x_ap[m], y_ap[m] = C.AP_TRUTH[sd]

    x = jp["x_m"].to_numpy()
    y = jp["y_m"].to_numpy()
    h = jp["heading_rad"].to_numpy()
    dist = np.hypot(x_ap - x, y_ap - y)
    world_ang = np.arctan2(y_ap - y, x_ap - x)
    angle_ego = _wrap_to_pi(world_ang - h)
    sin_ap = np.sin(angle_ego)
    cos_ap = np.cos(angle_ego)
    in_fov = (angle_ego >= fov_min_rad) & (angle_ego <= fov_max_rad)

    clutter_toward_ap = np.full(n, np.nan, dtype=np.float32)
    print(f"  ap_relative: scanning {n:,} rows for clutter_frac_toward_AP...")
    with h5py.File(C.LIDAR_H5, "r") as h5:
        ds = h5["distances"]
        for s_i in range(0, n, CHUNK_ROWS):
            e_i = min(s_i + CHUNK_ROWS, n)
            rows = jp["lidar_row"].iloc[s_i:e_i].to_numpy()
            order = np.argsort(rows)
            sorted_rows = rows[order]
            lo, hi = int(sorted_rows[0]), int(sorted_rows[-1]) + 1
            span = hi - lo
            if span <= 8 * (e_i - s_i):
                buf = ds[lo:hi]
                d = buf[sorted_rows - lo]
            else:
                d = np.empty((e_i - s_i, C.N_BEAMS), dtype=np.uint16)
                for k, r in enumerate(sorted_rows):
                    d[k] = ds[int(r)]
            inv_order = np.argsort(order)
            d_unsorted = d[inv_order]
            chunk_clutter = _compute_clutter_toward_ap_chunk(
                d_unsorted,
                angle_ego[s_i:e_i],
                in_fov[s_i:e_i],
                mask_invalid,
                beam_angles_rad,
                fov_min_rad, fov_max_rad,
                half_width_rad,
            )
            clutter_toward_ap[s_i:e_i] = chunk_clutter
            if s_i % (CHUNK_ROWS * 10) == 0:
                print(f"    ap_relative: {s_i}/{n}")

    df = pd.DataFrame({
        "joint_idx": np.arange(n, dtype=np.int64),
        "dist_to_AP": dist.astype(np.float32),
        "angle_to_AP_ego": angle_ego.astype(np.float32),
        "sin_angle_to_AP": sin_ap.astype(np.float32),
        "cos_angle_to_AP": cos_ap.astype(np.float32),
        "is_AP_in_FOV": in_fov,
        "clutter_frac_toward_AP": clutter_toward_ap,
    })
    df.to_parquet(CACHE_PATH, index=False)
    print(f"  -> wrote {CACHE_PATH}")
    return df


if __name__ == "__main__":
    compute_and_cache(force=True)
